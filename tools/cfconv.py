"""CHROME FORCE portraits: cf/src/*.png (Codex paintings) -> cf/cfports.js (SUPER-16 data).
Each portrait is cut to its own 15-colour palette in 9-bit colour (3 bits a channel), the way the cart's VDP would hold it,
in two sizes: 64x64 for the talk window and 48x48 for status screens. Pixels are stored one hex digit each (palette index 1-15).
usage: python -I tools/cfconv.py [preview.png]
"""
import os, sys, glob, json
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC, OUT = os.path.join(ROOT, 'cf', 'src'), os.path.join(ROOT, 'cf', 'cfports.js')
NAMES = os.path.join(SRC, 'names.json')  # file stem -> speaker name, written by tools/cfgen.js

def q9(a):
    return np.clip(np.round(a / 255 * 7), 0, 7) * 255 / 7

def palette(img, n=15, iters=16):
    """k-means over the 9-bit colours present, counts flattened (sqrt) so small bright details (eyes, screens, glows)
    keep a slot; seeded by farthest-point picks so every distinct hue starts with its own cluster"""
    px = q9(np.asarray(img, float).reshape(-1, 3))
    u, cnt = np.unique(px, axis=0, return_counts=True)
    w = np.sqrt(cnt)
    c = [u[cnt.argmax()]]
    for _ in range(min(n, len(u)) - 1):
        d = np.min([((u - x) ** 2).sum(1) for x in c], axis=0) * w
        c.append(u[d.argmax()])
    c = np.array(c, float)
    for _ in range(iters):
        d = ((u[:, None, :] - c[None, :, :]) ** 2).sum(2); lab = d.argmin(1)
        for k in range(len(c)):
            m = lab == k
            if m.any(): c[k] = (u[m] * w[m, None]).sum(0) / w[m].sum()
    return np.unique(q9(c), axis=0)

def index(img, pal):
    a = np.asarray(img, float).reshape(-1, 3)
    d = ((a[:, None, :] - pal[None, :, :]) ** 2).sum(2)
    return d.argmin(1).reshape(img.size[1], img.size[0]) + 1

def bust(src):
    """square crop: the art is already a square bust; trim a little margin so the face reads bigger"""
    w, h = src.size; m = int(min(w, h) * .04)
    return src.crop((m, 0, w - m, h - 2 * m))

def conv(path):
    im = bust(Image.open(path).convert('RGB'))
    out = {}
    for size, key in ((64, 'b'), (48, 's')):
        sm = im.resize((size, size), Image.LANCZOS)
        pal = palette(sm)
        idx = index(sm, pal)
        out[key] = {'p': ['#%02x%02x%02x' % tuple(int(v) for v in c) for c in pal], 'd': ''.join('%x' % v for v in idx.flatten())}
    return out

if __name__ == '__main__':
    names = json.load(open(NAMES)) if os.path.exists(NAMES) else {}
    data = {}
    for f in sorted(glob.glob(os.path.join(SRC, '*.png'))):
        stem = os.path.basename(f)[:-4]
        data[names.get(stem, stem.upper())] = conv(f)
        print('ok', stem)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write("'use strict';\n// CHROME FORCE portraits, generated by tools/cfconv.py from cf/src/*.png -- do not edit by hand.\n")
        fh.write('// name -> { b: 64x64 talk window, s: 48x48 status }, each { p: 15 colours (index 1-15), d: one hex digit a pixel }\n')
        fh.write('const CF_PORTS = {\n')
        for k, v in data.items():
            fh.write('  %s: %s,\n' % (json.dumps(k), json.dumps(v, separators=(',', ':'))))
        fh.write('};\n')
    if len(sys.argv) > 1:  # preview sheet, 4x
        ks = list(data); cols = 8; rows = (len(ks) + cols - 1) // cols
        sheet = Image.new('RGB', (cols * 66 * 4, rows * 66 * 4), (16, 16, 32))
        for i, k in enumerate(ks):
            b = data[k]['b']; pal = [(0, 0, 0)] + [tuple(int(h[j:j + 2], 16) for j in (1, 3, 5)) for h in b['p']]
            px = np.array([pal[int(ch, 16)] for ch in b['d']], np.uint8).reshape(64, 64, 3)
            sheet.paste(Image.fromarray(px).resize((256, 256), Image.NEAREST), ((i % cols) * 264 + 4, (i // cols) * 264 + 4))
        sheet.save(sys.argv[1]); print('preview', sys.argv[1])
    print(len(data), 'portraits ->', OUT)
