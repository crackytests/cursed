const TILECACHE = {};
function tileset(name) {
  if (TILECACHE[name]) return TILECACHE[name];
  const T = THEMES[name], out = { P: T.P, t: {} };
  for (const k in T) { if (k === 'P') continue; const v = T[k]; out.t[k] = Array.isArray(v) ? v.map(f => T16(f)) : [T16(v)]; }
  return TILECACHE[name] = out;
}
