// more room to ride: each battlefield grows ~18% by doubling its quietest interior rows and columns
// (walls, doors, bridges and set pieces are avoided where possible); every placement shifts with the map.
(function growBattles() {
  const busy = r => (r.match(/[#wd^*tb]/g) || []).length;
  const pick = (lines, n, avoid) => { const L = lines.length, ins = [];
    for (let k = 1; k <= n; k++) { const t = Math.round(k * L / (n + 1)); let best = -1, bs = 1e9;
      for (let i = Math.max(1, t - 2); i <= Math.min(L - 2, t + 2); i++) { if (ins.includes(i)) continue; const sc = busy(lines[i]) * 10 + (avoid.has(i) ? 25 : 0) + Math.abs(i - t); if (sc < bs) { bs = sc; best = i; } }
      if (best >= 0) ins.push(best); }
    return ins.sort((a, b) => a - b); };
  const dup = (lines, ins) => lines.flatMap((l, i) => ins.includes(i) ? [l, l] : [l]);
  const sh = (v, ins) => v + ins.filter(i => i < v).length;
  for (const id in BATTLES) {
    const D = BATTLES[id], w = Math.max(...D.map.map(r => r.length));
    let rows = D.map.map(r => (r + r[r.length - 1].repeat(w)).slice(0, w));
    const ry = pick(rows, Math.max(2, Math.round(rows.length * .18)), new Set(D.start.map(p => p[1])));
    rows = dup(rows, ry);
    let cols = [...Array(w)].map((_, x) => rows.map(r => r[x]).join(''));
    const cx = pick(cols, Math.max(2, Math.round(w * .18)), new Set(D.start.map(p => p[0])));
    cols = dup(cols, cx);
    D.map = rows.map((_, y) => cols.map(c => c[y]).join(''));
    const mv = p => { p[0] = sh(p[0], cx); p[1] = sh(p[1], ry); }, mvF = f => { f[1] = sh(f[1], cx); f[2] = sh(f[2], ry); };
    D.start.forEach(mv); D.chests.forEach(mv); D.foes.forEach(mvF); (D.waves || []).forEach(wv => wv[1].forEach(mvF));
  }
})();

