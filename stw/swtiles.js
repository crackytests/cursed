// a built tileset: { P, t: { char: [frames] } }. The corrupted save crushes every palette to four greens.
function swTileset(name) {
  if (SWTILECACHE[name]) return SWTILECACHE[name];
  const T = SWTHEMES[name], out = { P: T.P, t: {} };
  for (const k in T) { if (k === 'P') continue; const v = T[k]; out.t[k] = Array.isArray(v) ? v.map(f => TS16(f)) : [TS16(v)]; }
  return SWTILECACHE[name] = out;
}

