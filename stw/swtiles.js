  water: (g, a, b, c, f) => { g.r(0, 0, 16, 16, a); for (let y = 1; y < 16; y += 4) for (let x = 0; x < 16; x++) if (Math.sin((x + f * 4 + y * 3) * .45) > .75) g.p(x, y, b); g.p((f * 5 + 2) % 16, (f * 7 + 4) % 16, c); },
